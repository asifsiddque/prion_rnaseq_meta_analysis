#' Write a coldata CSV and print a summary.
write_coldata <- function(df, gse_id, out_dir = OUTPUT_DIR) {
  out_path <- file.path(out_dir, paste0(gse_id, "_coldata.csv"))
  write_csv(df, out_path)
  cat(sprintf("  [%s] Written: %s (%d samples)\n", gse_id, out_path, nrow(df)))
  cat(sprintf("  [%s] Condition counts: %s\n", gse_id,
              paste(names(table(df$condition)), table(df$condition), sep = "=", collapse = ", ")))
  invisible(df)
}


#' Build GSM->SRR map for a study by resolving SRX->SRR via Entrez.
#' Also cross-checks against sample_metadata.tsv (which has the ground-truth SRRs).
#' Returns a data.frame with columns: gsm_id, srx_id, srr_id.
build_gsm_srr_map <- function(gse_obj, gse_id) {
  cat(sprintf("  [%s] Resolving GSM -> SRX -> SRR for %d samples...\n",
              gse_id, length(gse_obj$gsms)))

  # Get the SRRs we already know about from sample_metadata.tsv
  known_srrs <- sample_meta %>%
    filter(GSE == gse_id) %>%
    pull(SRR)

  rows <- lapply(names(gse_obj$gsms), function(gsm_id) {
    gsm <- gse_obj$gsms[[gsm_id]]
    srx <- extract_srx(gsm)
    data.frame(gsm_id = gsm_id, srx_id = srx, stringsAsFactors = FALSE)
  })
  gsm_srx_df <- bind_rows(rows)

  # Resolve SRX -> SRR
  cat(sprintf("  [%s] Resolving %d SRX accessions via NCBI Entrez...\n",
              gse_id, sum(!is.na(gsm_srx_df$srx_id))))

  gsm_srx_df$srr_id <- sapply(gsm_srx_df$srx_id, function(srx) {
    if (is.na(srx)) return(NA_character_)
    srr <- srx_to_srr(srx)
    return(srr)
  })

  # Validate: all resolved SRRs should be in sample_metadata.tsv
  resolved_srrs <- gsm_srx_df$srr_id[!is.na(gsm_srx_df$srr_id)]
  missing_from_meta <- setdiff(resolved_srrs, known_srrs)
  missing_from_geo  <- setdiff(known_srrs, resolved_srrs)

  if (length(missing_from_meta) > 0) {
    warning(sprintf(
      "[%s] %d SRRs resolved from GEO but NOT in sample_metadata.tsv: %s",
      gse_id, length(missing_from_meta),
      paste(head(missing_from_meta, 5), collapse = ", ")
    ))
  }
  if (length(missing_from_geo) > 0) {
    warning(sprintf(
      "[%s] %d SRRs in sample_metadata.tsv but NOT resolved from GEO: %s",
      gse_id, length(missing_from_geo),
      paste(head(missing_from_geo, 5), collapse = ", ")
    ))
  }

  n_resolved <- sum(!is.na(gsm_srx_df$srr_id))
  cat(sprintf("  [%s] Resolved %d/%d SRX->SRR mappings.\n",
              gse_id, n_resolved, nrow(gsm_srx_df)))

  return(gsm_srx_df)
}

