srx_cache <- new.env(hash = TRUE, parent = emptyenv())

srx_to_srr <- function(srx_id) {
  if (is.na(srx_id) || nchar(srx_id) == 0) return(NA_character_)

  # Tier 1: check hard-coded fallback map (covers all 867 known samples)
  if (srx_id %in% names(SRX_SRR_FALLBACK)) {
    return(SRX_SRR_FALLBACK[[srx_id]])
  }

  # Tier 2: check in-memory cache (for any SRX resolved via API in this session)
  if (exists(srx_id, envir = srx_cache)) {
    return(get(srx_id, envir = srx_cache))
  }

  Sys.sleep(API_SLEEP)

  # Step 1: esearch to get internal SRA UID
  api_key_param <- if (nchar(NCBI_API_KEY) > 0) paste0("&api_key=", NCBI_API_KEY) else ""
  search_url <- paste0(
    "https://eutils.ncbi.nlm.nih.gov/entrez/eutils/esearch.fcgi",
    "?db=sra&term=", srx_id, "&retmax=5&retmode=json", api_key_param
  )

  search_resp <- tryCatch(
    GET(search_url, timeout(15)),
    error = function(e) NULL
  )
  if (is.null(search_resp) || status_code(search_resp) != 200) {
    warning(sprintf("esearch failed for %s", srx_id))
    return(NA_character_)
  }

  search_data <- fromJSON(content(search_resp, "text", encoding = "UTF-8"))
  uids <- search_data$esearchresult$idlist
  if (length(uids) == 0) {
    warning(sprintf("No SRA UID found for %s", srx_id))
    return(NA_character_)
  }

  Sys.sleep(API_SLEEP)

  # Step 2: efetch RunInfo to get SRR
  fetch_url <- paste0(
    "https://eutils.ncbi.nlm.nih.gov/entrez/eutils/efetch.fcgi",
    "?db=sra&id=", uids[1], "&rettype=runinfo&retmode=text", api_key_param
  )

  fetch_resp <- tryCatch(
    GET(fetch_url, timeout(15)),
    error = function(e) NULL
  )
  if (is.null(fetch_resp) || status_code(fetch_resp) != 200) {
    warning(sprintf("efetch failed for %s (UID %s)", srx_id, uids[1]))
    return(NA_character_)
  }

  content_text <- content(fetch_resp, "text", encoding = "UTF-8")
  lines <- str_split(str_trim(content_text), "\n")[[1]]
  lines <- lines[nchar(lines) > 0]

  if (length(lines) < 2) {
    warning(sprintf("RunInfo empty for %s", srx_id))
    return(NA_character_)
  }

  header <- str_split(lines[1], ",")[[1]]
  values <- str_split(lines[2], ",")[[1]]
  run_row <- setNames(as.list(values), header)
  srr <- run_row[["Run"]]

  if (is.null(srr) || is.na(srr) || nchar(srr) == 0) {
    warning(sprintf("No Run field in RunInfo for %s", srx_id))
    return(NA_character_)
  }

  # Cache the result
  assign(srx_id, srr, envir = srx_cache)
  return(srr)
}


