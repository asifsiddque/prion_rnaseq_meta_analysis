coldata_210128 <- lapply(names(gse210128$gsms), function(gsm_id) {
  gsm        <- gse210128$gsms[[gsm_id]]
  chars      <- parse_characteristics(gsm)
  gsm_title  <- str_to_lower(str_trim(GEOquery::Meta(gsm)$title[[1]]))
  srr        <- gsm_srr_210128$srr_id[gsm_srr_210128$gsm_id == gsm_id]
  if (length(srr) == 0 || is.na(srr)) return(NULL)

  treatment <- str_to_lower(chars[["treatment"]])
  condition <- case_when(
    str_detect(treatment, "nbh|control|mock|sham") ~ "control",
    str_detect(treatment, "rml|prion|scrapie")     ~ "prion",
    TRUE ~ NA_character_
  )

  tissue_raw <- str_to_lower(str_trim(chars[["tissue"]]))
  tissue <- case_when(
    str_detect(tissue_raw, "blood")   ~ "whole_blood",
    str_detect(tissue_raw, "spleen")  ~ "spleen",
    str_detect(tissue_raw, "muscle")  ~ "skeletal_muscle",
    TRUE ~ tissue_raw
  )

  tp_raw <- str_extract(gsm_title, "(\\d+|term)\\s*wpi")
  time_point_wpi <- if (!is.na(tp_raw)) {
    tp_num <- str_extract(tp_raw, "\\d+|term")
    if (tp_num == "term") 22L else as.integer(tp_num)
  } else {
    NA_integer_
  }

  cohort <- case_when(
    str_detect(gsm_title, "validation cohort") ~ "validation",
    str_detect(gsm_title, "main cohort")       ~ "main",
    TRUE ~ NA_character_
  )

  data.frame(
    sample_id      = srr,
    files          = quant_path(srr, "GSE210128"),
    condition      = condition,
    tissue         = tissue,
    time_point_wpi = time_point_wpi,
    cohort         = cohort,
    gsm_id         = gsm_id,
    stringsAsFactors = FALSE
  )
}) %>% bind_rows() %>% filter(!is.na(condition))

