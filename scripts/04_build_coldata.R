#' Fetch GEO series object via GEOquery with local caching.
#' Uses GSEMatrix=FALSE to download the full SOFT file, which is required to
#' populate Meta(gsm)$characteristics_ch1 and Meta(gsm)$relation for all GSMs.
#' (GSEMatrix=TRUE only downloads the series matrix and does NOT include per-sample
#'  SOFT metadata such as characteristics_ch1 — it would silently return empty lists.)
#' Returns a list with element $gsms (named list of GSM objects) to keep the
#' rest of the script's interface identical to the original GEOparse version.
fetch_geo <- function(gse_id, cache_dir = GEO_CACHE_DIR) {
  cat(sprintf("  Fetching GEO metadata for %s (SOFT file)...\n", gse_id))
  gse_obj <- tryCatch(
    GEOquery::getGEO(gse_id, destdir = cache_dir, GSEMatrix = FALSE,
                     getGPL = FALSE),
    error = function(e) {
      stop(sprintf("Failed to fetch GEO data for %s: %s", gse_id, e$message))
    }
  )
  # With GSEMatrix=FALSE, getGEO() returns a GSE object directly.
  # GSMList() extracts the named list of GSM objects with full Meta() populated.
  gsm_list <- GEOquery::GSMList(gse_obj)
  gse <- list(gsms = gsm_list)
  cat(sprintf("  %s: %d GSM samples found.\n", gse_id, length(gse$gsms)))
  return(gse)
}


#' Extract characteristics from a GSM object into a named list.
#' Handles the "key: value" format used in GEO series matrices.
#' GEOquery: characteristics are in Meta(gsm)$characteristics_ch1
parse_characteristics <- function(gsm) {
  chars <- GEOquery::Meta(gsm)$characteristics_ch1
  if (is.null(chars) || length(chars) == 0) return(list())
  result <- list()
  for (ch in chars) {
    parts <- str_split_fixed(ch, ":\\s*", 2)
    if (ncol(parts) == 2 && nchar(parts[1,1]) > 0) {
      key <- str_trim(str_to_lower(parts[1,1]))
      val <- str_trim(parts[1,2])
      result[[key]] <- val
    }
  }
  return(result)
}


#' Extract SRX accession from GSM relation field.
#' GEOquery: relation field is in Meta(gsm)$relation
extract_srx <- function(gsm) {
  relations <- GEOquery::Meta(gsm)$relation
  if (is.null(relations)) return(NA_character_)
  sra_links <- relations[str_detect(relations, "SRX")]
  if (length(sra_links) == 0) return(NA_character_)
  srx <- str_extract(sra_links[1], "SRX\\d+")
  return(srx)
}


